<#
.SYNOPSIS
    Build the self-contained setup EXE (ADCS-CDBRP-Provider-Setup-<ver>-<arch>.exe).

.DESCRIPTION
    The setup embeds the provider DLL, uitest.exe, the install/sync scripts and the license
    as RCDATA resources, then runs the same install.ps1 that the repository ships. The
    installer only extracts, elevates and forwards arguments, so the install logic has
    exactly one implementation.

    Payload staging and resource compilation happen in an ASCII-only temporary directory:
    rc.exe cannot resolve resource filenames that contain non-ASCII characters, and the
    repository path is allowed to contain them.

.EXAMPLE
    pwsh -File scripts/build-installer.ps1

.EXAMPLE
    pwsh -File scripts/build-installer.ps1 -Arch x86 -Version 2.0.0
#>
[CmdletBinding()]
param(
    [ValidateSet('x64', 'x86', 'arm64')]
    [string]$Arch = 'x64',

    [string]$Version = '2.0.0',

    [string]$OutDir,

    [switch]$SkipBuild,

    # Keep the staging directory (diagnostics)
    [switch]$KeepStage
)

$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path -Parent $PSScriptRoot
if (-not $OutDir) { $OutDir = Join-Path $RepoRoot 'dist' }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

# ------------------------------------------------------------------ 1. provider build
$dll = Join-Path $RepoRoot "out\$Arch\OcspDbProvider.dll"
$uit = Join-Path $RepoRoot "out\$Arch\uitest.exe"
$cfg = Join-Path $RepoRoot "out\$Arch\OcspConfig.exe"
if (-not $SkipBuild -or -not (Test-Path $dll) -or -not (Test-Path $uit) -or -not (Test-Path $cfg)) {
    & (Join-Path $PSScriptRoot 'build.ps1') -Arch $Arch
} else {
    Write-Host "using existing provider build: $dll"
}
foreach ($f in @($dll, $uit, $cfg)) {
    if (-not (Test-Path $f)) { throw "missing payload file: $f" }
}

# ------------------------------------------------------------------ 2. stage payload (ASCII path)
$stage = Join-Path $env:TEMP ("adcs-cdbrp-setup-build-" + $Arch)
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
$payloadDir = Join-Path $stage 'payload'
New-Item -ItemType Directory -Force -Path $payloadDir | Out-Null

Copy-Item $dll                                       (Join-Path $payloadDir 'OcspDbProvider.dll') -Force
Copy-Item $uit                                       (Join-Path $payloadDir 'uitest.exe')          -Force
Copy-Item (Join-Path $RepoRoot 'scripts\install.ps1') (Join-Path $payloadDir 'install.ps1')        -Force
Copy-Item (Join-Path $RepoRoot 'scripts\sync.ps1')    (Join-Path $payloadDir 'sync.ps1')           -Force
Copy-Item (Join-Path $RepoRoot 'LICENSE')             (Join-Path $payloadDir 'LICENSE')            -Force
Copy-Item (Join-Path $RepoRoot "out\$Arch\OcspConfig.exe") (Join-Path $payloadDir 'OcspConfig.exe') -Force
Copy-Item (Join-Path $RepoRoot 'src\setup\setup.manifest') (Join-Path $stage 'setup.manifest')     -Force

# ------------------------------------------------------------------ 3. generated version header
$machine = @{ x64 = 'X64'; x86 = 'X86'; arm64 = 'ARM64' }[$Arch]
$header = @(
    '// generated by scripts/build-installer.ps1 - do not edit',
    ('#define SETUP_VERSION  L"' + $Version + '"'),
    ('#define SETUP_ARCH     L"' + $Arch + '"'),
    ('#define SETUP_ARCH_DIR L"' + $Arch + '"')
)
[System.IO.File]::WriteAllLines((Join-Path $stage 'setup_version.h'), $header,
                                (New-Object System.Text.ASCIIEncoding))

# ------------------------------------------------------------------ 4. generated resource script
# rc' C-style parser treats backslashes in quoted filenames as escapes (\A, \T, ...),
# so every backslash has to be doubled before it goes into the .rc
$quote = { param($p) '"' + ($p -replace '\\', '\\\\') + '"' }
$rc = @(
    '// generated by scripts/build-installer.ps1 - do not edit',
    '#include <windows.h>',
    '',
    # 1 24 = RT_MANIFEST. Use the numeric type on purpose: RT_MANIFEST expands to
    # MAKEINTRESOURCE(24), which the resource compiler does not always accept.
    ('1 24 '            + (& $quote (Join-Path $stage 'setup.manifest'))),
    ('1001 RCDATA '     + (& $quote (Join-Path $payloadDir 'install.ps1'))),
    ('1002 RCDATA '     + (& $quote (Join-Path $payloadDir 'sync.ps1'))),
    ('1003 RCDATA '     + (& $quote (Join-Path $payloadDir 'OcspDbProvider.dll'))),
    ('1004 RCDATA '     + (& $quote (Join-Path $payloadDir 'uitest.exe'))),
    ('1005 RCDATA '     + (& $quote (Join-Path $payloadDir 'LICENSE'))),
    ('1006 RCDATA '     + (& $quote (Join-Path $payloadDir 'OcspConfig.exe'))),
    '',
    '1 VERSIONINFO',
    ('FILEVERSION '    + (($Version -replace '\.', ',') + ',0')),
    ('PRODUCTVERSION ' + (($Version -replace '\.', ',') + ',0')),
    'FILEFLAGSMASK 0x3fL',
    'FILEFLAGS 0x0L',
    'FILEOS 0x40004L',
    'FILETYPE 0x1L',
    'BEGIN',
    '    BLOCK "StringFileInfo"',
    '    BEGIN',
    '        BLOCK "040904b0"',
    '        BEGIN',
    '            VALUE "CompanyName", "4625tracker"',
    ('            VALUE "FileDescription", "ADCS CDBRP Provider setup (' + $Arch + ')"'),
    ('            VALUE "FileVersion", "' + $Version + '"'),
    '            VALUE "LegalCopyright", "MIT License"',
    ('            VALUE "OriginalFilename", "ADCS-CDBRP-Provider-Setup-' + $Version + '-' + $Arch + '.exe"'),
    '            VALUE "ProductName", "ADCS CDBRP Provider"',
    ('            VALUE "ProductVersion", "' + $Version + '"'),
    '        END',
    '    END',
    '    BLOCK "VarFileInfo"',
    '    BEGIN',
    '        VALUE "Translation", 0x409, 1200',
    '    END',
    'END'
)
[System.IO.File]::WriteAllLines((Join-Path $stage 'Setup.rc'), $rc,
                                (New-Object System.Text.UnicodeEncoding))

# ------------------------------------------------------------------ 5. compile
$vcvars = $null
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (Test-Path $vswhere) {
    $root = & $vswhere -products * -prerelease -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 `
                       -property installationPath 2>$null | Select-Object -First 1
    if ($root) {
        $names = switch ($Arch) {
            'x64'   { @('vcvars64.bat') }
            'x86'   { @('vcvarsamd64_x86.bat', 'vcvars32.bat') }
            'arm64' { @('vcvarsamd64_arm64.bat') }
        }
        foreach ($n in $names) {
            $p = Join-Path $root ('VC\Auxiliary\Build\' + $n)
            if (Test-Path $p) { $vcvars = $p; break }
        }
    }
}
if (-not $vcvars) { throw "vcvars for $Arch not found (install the $Arch C++ build tools)" }

$exe = Join-Path $OutDir ("ADCS-CDBRP-Provider-Setup-{0}-{1}.exe" -f $Version, $Arch)
$res = Join-Path $stage 'Setup.res'

$cmd = @(
    ('call "' + $vcvars + '" >nul'),
    ('cd /d "' + $stage + '"'),
    ('rc /nologo /fo "' + $res + '" Setup.rc'),
    ('cl /nologo /EHsc /O2 /W3 /MT /utf-8 /DUNICODE /D_UNICODE /D_CRT_SECURE_NO_WARNINGS ' +
     '/I"' + $stage + '" /Fe:"' + $exe + '" "' + (Join-Path $RepoRoot 'src\setup\Setup.cpp') + '" "' + $res + '" ' +
     '/link /SUBSYSTEM:CONSOLE /MACHINE:' + $machine +
     ' shell32.lib advapi32.lib ole32.lib user32.lib')
) -join ' && '

Write-Host "--- building setup ($Arch)"
cmd /c $cmd
if ($LASTEXITCODE -ne 0) { throw "setup build failed with exit code $LASTEXITCODE" }
if (-not (Test-Path $exe)) { throw "missing output: $exe" }

$hash = Get-FileHash $exe -Algorithm SHA256
Write-Host ''
Write-Host ("built : " + (Split-Path $exe -Leaf) + "  " + (Get-Item $exe).Length + " B")
Write-Host ("sha256: " + $hash.Hash.ToLower())
Write-Host ("path  : " + $exe)

if (-not $KeepStage) { Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue }
